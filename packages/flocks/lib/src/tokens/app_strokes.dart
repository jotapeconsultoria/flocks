/// Stroke width tokens for App.
///
/// A clean 2× scale from a hairline (0.5) to a heavy rule (8.0).
sealed class AppStrokes {
  /// The stroke width value for no stroke. (0.0)
  static const double none = 0.0;

  /// The extra small (hairline) stroke width. (0.5)
  static const double xs = 0.5;

  /// The small stroke width. (1.0)
  static const double s = 1.0;

  /// The medium stroke width. (2.0)
  static const double m = 2.0;

  /// The large stroke width. (4.0)
  static const double l = 4.0;

  /// The extra large stroke width. (8.0)
  static const double xl = 8.0;
}
